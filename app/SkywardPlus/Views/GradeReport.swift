import AppKit
import SwiftUI
import UniformTypeIdentifiers

/// A printable summary of every class: grades in each marking period, the
/// current average, categories and missing work.
struct GradeReportView: View {
    let profileName: String
    let school: String
    let data: StudentData
    let courses: [Course]
    let lit: String?
    let gpa: GPAResult
    let goals: [String: Double]
    let generated: Date

    private var columns: [TermBucket] {
        data.buckets.filter { bucket in courses.contains { !($0.grade(bucket.lit)?.isEmpty ?? true) } }
    }

    var body: some View {
        VStack(alignment: .leading, spacing: 22) {
            header
            gradeTable
            if let lit { details(lit) }
            Text("Generated by Skyward Plus from Skyward on \(generated.formatted(date: .long, time: .shortened)). Unofficial: check Skyward for official grades.")
                .font(.system(size: 8))
                .foregroundStyle(.gray)
        }
        .padding(40)
        .frame(width: 612, alignment: .topLeading)
        .background(Color.white)
        .environment(\.colorScheme, .light)
    }

    private var header: some View {
        HStack(alignment: .bottom) {
            VStack(alignment: .leading, spacing: 3) {
                Text("Grade Report").font(.system(size: 22, weight: .bold))
                Text([profileName, school].filter { !$0.isEmpty }.joined(separator: " · "))
                    .font(.system(size: 11)).foregroundStyle(.gray)
            }
            Spacer()
            VStack(alignment: .trailing, spacing: 3) {
                Text("GPA \(Fmt.gpa(gpa.weighted))").font(.system(size: 15, weight: .semibold).monospacedDigit())
                Text("Unweighted \(Fmt.gpa(gpa.unweighted))").font(.system(size: 10).monospacedDigit()).foregroundStyle(.gray)
            }
        }
        .overlay(alignment: .bottom) { Rectangle().fill(Color.black).frame(height: 1.5).offset(y: 8) }
        .padding(.bottom, 6)
    }

    private var gradeTable: some View {
        let cols = columns
        return VStack(spacing: 0) {
            HStack(spacing: 0) {
                Text("Class").frame(maxWidth: .infinity, alignment: .leading)
                ForEach(cols) { Text($0.lit).frame(width: cellWidth(cols.count), alignment: .trailing) }
            }
            .font(.system(size: 8, weight: .semibold))
            .foregroundStyle(.gray)
            .padding(.vertical, 5)
            ForEach(Array(courses.enumerated()), id: \.element.id) { index, course in
                HStack(spacing: 0) {
                    VStack(alignment: .leading, spacing: 1) {
                        Text(Str.titleCase(course.name)).font(.system(size: 9.5, weight: .medium)).lineLimit(1)
                        Text([course.period.isEmpty ? "" : "Period \(course.period)", Str.titleCase(course.teacher)].filter { !$0.isEmpty }.joined(separator: " · "))
                            .font(.system(size: 7.5)).foregroundStyle(.gray).lineLimit(1)
                    }
                    .frame(maxWidth: .infinity, alignment: .leading)
                    ForEach(cols) { bucket in
                        let text = course.grade(bucket.lit)?.text ?? ""
                        Text(text.isEmpty ? "–" : text)
                            .font(.system(size: 9.5, weight: bucket.lit == lit ? .bold : .regular).monospacedDigit())
                            .foregroundStyle(text.isEmpty ? Color.gray.opacity(0.5) : reportColor(Double(text)))
                            .frame(width: cellWidth(cols.count), alignment: .trailing)
                    }
                }
                .padding(.vertical, 5)
                .background(index.isMultiple(of: 2) ? Color.black.opacity(0.03) : .clear)
            }
        }
    }

    private func cellWidth(_ count: Int) -> CGFloat { min(34, 300 / CGFloat(max(count, 1))) }

    private func reportColor(_ value: Double?) -> Color {
        guard let value else { return .black }
        return value < 70 ? Color(red: 0.75, green: 0.1, blue: 0.1) : .black
    }

    @ViewBuilder
    private func details(_ lit: String) -> some View {
        let withDetail = courses.compactMap { course -> (Course, GradeDetail)? in
            guard let detail = data.detail(course.id, lit) else { return nil }
            return (course, detail)
        }
        if !withDetail.isEmpty {
            VStack(alignment: .leading, spacing: 14) {
                Text("\(data.bucket(lit)?.displayName ?? lit) details").font(.system(size: 13, weight: .semibold))
                ForEach(withDetail, id: \.0.id) { course, detail in
                    VStack(alignment: .leading, spacing: 4) {
                        HStack {
                            Text(Str.titleCase(course.name)).font(.system(size: 10, weight: .semibold))
                            Spacer()
                            if let goal = goals[course.id] {
                                Text("Goal \(Fmt.percent(goal))").font(.system(size: 8)).foregroundStyle(.gray)
                            }
                            Text(detail.percent.map { Fmt.percent($0, digits: 2) } ?? detail.gradeText)
                                .font(.system(size: 10, weight: .semibold).monospacedDigit())
                        }
                        let categories = detail.categories.map { c in
                            "\(c.name)\(c.weight.map { " (\(Fmt.percent($0))%)" } ?? ""): \(c.percent.map { Fmt.percent($0) } ?? "–")"
                        }
                        if !categories.isEmpty {
                            Text(categories.joined(separator: "   ")).font(.system(size: 8)).foregroundStyle(.gray)
                        }
                        let missing = detail.assignments.filter(\.missing)
                        if !missing.isEmpty {
                            Text("Missing: " + missing.map(\.name).joined(separator: ", "))
                                .font(.system(size: 8)).foregroundStyle(Color(red: 0.75, green: 0.1, blue: 0.1))
                        }
                    }
                    .padding(.bottom, 4)
                    .overlay(alignment: .bottom) { Rectangle().fill(Color.black.opacity(0.08)).frame(height: 0.5) }
                }
            }
        }
    }
}

enum GradeReportExporter {
    /// Renders the report to a multi-page US Letter PDF.
    @MainActor
    static func pdfData(for view: GradeReportView) -> Data? {
        let renderer = ImageRenderer(content: view)
        renderer.proposedSize = ProposedViewSize(width: 612, height: nil)
        let data = NSMutableData()
        renderer.render { size, draw in
            let page = CGRect(x: 0, y: 0, width: 612, height: 792)
            var box = page
            guard let consumer = CGDataConsumer(data: data as CFMutableData),
                  let context = CGContext(consumer: consumer, mediaBox: &box, nil) else { return }
            let pages = max(1, Int(ceil(size.height / page.height)))
            for index in 0..<pages {
                context.beginPDFPage(nil)
                context.setFillColor(CGColor(gray: 1, alpha: 1))
                context.fill(page)
                // SwiftUI draws from the bottom-left; shift so this page's slice is visible.
                let offset = size.height - page.height * CGFloat(index + 1)
                context.translateBy(x: 0, y: -offset)
                draw(context)
                context.endPDFPage()
            }
            context.closePDF()
        }
        return data.length > 0 ? data as Data : nil
    }
}

extension AppModel {
    /// Asks where to save, then writes the grade report as a PDF.
    func exportReport() {
        guard let profile = active else { return }
        let lit = selectedLit
        let entries = lit.map { GPA.currentEntries(data: data, lit: $0, settings: prefs.gpa) } ?? []
        let view = GradeReportView(
            profileName: profile.name, school: data.profile.school, data: data,
            courses: courses.filter { course in data.buckets.contains { !(course.grade($0.lit)?.isEmpty ?? true) } },
            lit: lit, gpa: GPA.compute(entries), goals: prefs.goals, generated: now()
        )
        guard let pdf = GradeReportExporter.pdfData(for: view) else { return }
        let panel = NSSavePanel()
        panel.allowedContentTypes = [.pdf]
        panel.nameFieldStringValue = "\(profile.name) Grade Report.pdf"
        panel.canCreateDirectories = true
        guard panel.runModal() == .OK, let url = panel.url else { return }
        do {
            try pdf.write(to: url, options: .atomic)
            NSWorkspace.shared.activateFileViewerSelecting([url])
        } catch {
            NSSound.beep()
        }
    }
}
